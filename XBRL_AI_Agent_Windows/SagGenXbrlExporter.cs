    private static string EscapeXml(string val) =>
        (val ?? "")
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;")
            .Replace("\"", "&quot;")
            .Replace("'", "&apos;");

    private static string EscapeCsv(string val)
    {
        val ??= "";
        if (val.Contains(',') || val.Contains('"') || val.Contains('\n') || val.Contains('\r'))
            return $"\"{val.Replace("\"", "\"\"")}\"";
        return val;
    }
